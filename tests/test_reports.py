    def test_pdf_generation_magic_bytes_and_demo_watermark(self):
        """Verifies PDF report generation compiles valid PDF byte stream with watermark."""
        pdf_bytes = generate_pdf_report(
            scan_meta=self.mock_meta,
            devices=self.mock_devices,
            services=self.mock_services,
            findings=self.mock_findings,
            risk_data=self.mock_risk
        )
        self.assertIsInstance(pdf_bytes, bytes)
        self.assertTrue(pdf_bytes.startswith(b"%PDF-"), "Generated byte sequence does not begin with %PDF-")
        self.assertTrue(len(pdf_bytes) > 1000)

    def test_csv_generation_structure(self):
        """Verifies CSV generation includes required columns and headers."""
        csv_str = generate_csv_report(
            scan_meta=self.mock_meta,
            findings=self.mock_findings,
            services=self.mock_services,
            devices=self.mock_devices
        )
        self.assertIsInstance(csv_str, str)
        self.assertIn("Scan_ID,Timestamp,Target_IP,Scan_Mode,Rule_ID", csv_str)
        self.assertIn("CCTV-RTSP-001", csv_str)

    def test_json_generation_valid_json(self):
        """Verifies JSON report produces valid, parseable schema."""
        json_str = generate_json_report(
            scan_meta=self.mock_meta,
            devices=self.mock_devices,
            services=self.mock_services,
            findings=self.mock_findings,
            risk_data=self.mock_risk
        )
        data = json.loads(json_str)
        self.assertEqual(data["generator"]["application"], "IoT Sentinel Pro — Campus Edition")
        self.assertEqual(data["scan_metadata"]["scan_id"], "TEST-ADV-RPT-001")
        self.assertEqual(len(data["vulnerability_findings"]), 1)

    def test_scan_comparator_engine(self):
        """Verifies delta analysis between baseline and current scan snapshots."""
        temp_db = tempfile.NamedTemporaryFile(suffix=".db", delete=False)
        db_path = temp_db.name
        temp_db.close()
        init_db(db_path)

        try:
            # Baseline Scan A: Port 80
            save_scan_record(
                scan_id="SCAN-A", target="192.168.1.50", scan_type="vulnerability", status="completed",
                total_hosts=1, total_ports=1, total_findings=1, risk_score=20.0, duration_sec=1.0, is_demo=True,
                devices=[{"ip_address": "192.168.1.50"}],
                services=[{"device_ip": "192.168.1.50", "port": 80}],
                vulnerabilities=[{"device_ip": "192.168.1.50", "rule_id": "IOT-SEC-003", "port": 80, "severity": "MEDIUM", "title": "HTTP Cleartext"}],
                db_file=db_path
            )

            # Current Scan B: Port 80 and new Port 23 (Telnet)
            save_scan_record(
                scan_id="SCAN-B", target="192.168.1.50", scan_type="vulnerability", status="completed",
                total_hosts=1, total_ports=2, total_findings=2, risk_score=55.0, duration_sec=1.2, is_demo=True,
                devices=[{"ip_address": "192.168.1.50"}],
                services=[{"device_ip": "192.168.1.50", "port": 80}, {"device_ip": "192.168.1.50", "port": 23}],
                vulnerabilities=[
                    {"device_ip": "192.168.1.50", "rule_id": "IOT-SEC-003", "port": 80, "severity": "MEDIUM", "title": "HTTP Cleartext"},
                    {"device_ip": "192.168.1.50", "rule_id": "IOT-SEC-001", "port": 23, "severity": "CRITICAL", "title": "Telnet Exposed"}
                ],
                db_file=db_path
            )

            diff = ScanComparator.compare_scans("SCAN-A", "SCAN-B", db_file=db_path)
            self.assertFalse(diff.get("is_partial_scan"))
            self.assertEqual(len(diff["new_ports"]), 1)
            self.assertEqual(diff["new_ports"][0]["port"], 23)
            self.assertEqual(len(diff["new_findings"]), 1)
            self.assertEqual(diff["new_findings"][0]["rule_id"], "IOT-SEC-001")
            self.assertEqual(diff["score_delta"], 35.0)

        finally:
            if os.path.exists(db_path):
                os.remove(db_path)

    def test_network_overview_manager(self):
        """Verifies policy deviation detection and zone aggregation."""
        devices = [
            {"ip_address": "192.168.1.105", "device_type": "CCTV / IP Camera", "expected_zone": "Surveillance Zone (CCTV)"}
        ]
        services = [
            {"device_ip": "192.168.1.105", "port": 554, "state": "open"},
            {"device_ip": "192.168.1.105", "port": 23, "state": "open"}  # Policy deviation!
        ]
        overview = NetworkOverviewManager.generate_network_overview(devices, services)
        self.assertEqual(overview["total_nodes_observed"], 1)
        self.assertTrue(len(overview["policy_deviations"]) >= 1)
        self.assertEqual(overview["policy_deviations"][0]["severity"], "CRITICAL")

    def test_cve_lookup_offline_graceful_handling(self):
        """Verifies CVELookup handles unreachable servers gracefully without unhandled exceptions."""
        client = CVELookup(timeout=1)
        client.base_url = "http://127.0.0.1:54321/unreachable"
        res = client.lookup_cves_for_service("boa", "0.94.14")
        self.assertEqual(res["status"], "OFFLINE_FALLBACK")
        self.assertEqual(res["cves"], [])

